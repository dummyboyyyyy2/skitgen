// ─── Relevance scoring, used to trim strongest_comedic_instincts / comedy_modes
// down to whichever ones actually bear on the current topic, instead of always
// dumping the entire learned profile into every prompt. Pure keyword overlap —
// no extra model call, so it costs nothing.
const DNA_STOPWORDS = new Set([
  "the", "a", "an", "and", "or", "but", "of", "in", "on", "at", "to", "for",
  "with", "is", "are", "was", "were", "be", "been", "this", "that", "he",
  "she", "it", "his", "her", "its", "when", "while", "about", "into", "from",
  "as", "if", "so", "just", "really", "very", "get", "gets", "got", "like",
  "because", "your", "you", "there", "their", "them", "than",
]);

function tokenizeForRelevance(str) {
  return String(str || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !DNA_STOPWORDS.has(w));
}

function relevanceScore(text, queryTokenSet) {
  if (!text || !queryTokenSet.size) return 0;
  const textTokens = tokenizeForRelevance(text);
  let score = 0;
  for (const t of textTokens) if (queryTokenSet.has(t)) score += 1;
  return score;
}

// Picks the top N items by relevance to `focus`. If focus is empty, or fewer
// than `keep` items exist, or nothing scores above 0 (topic shares no real
// vocabulary with the DNA yet — e.g. a brand-new profile), returns the
// original list untouched rather than guessing.
function trimByRelevance(items, keep, focus, textOf) {
  if (!Array.isArray(items) || items.length <= keep || !focus) return items;
  const queryTokens = new Set(tokenizeForRelevance(focus));
  if (!queryTokens.size) return items;
  const scored = items.map((item, i) => ({ item, i, score: relevanceScore(textOf(item), queryTokens) }));
  if (!scored.some((s) => s.score > 0)) return items;
  return scored
    .sort((a, b) => b.score - a.score || a.i - b.i)
    .slice(0, keep)
    .sort((a, b) => a.i - b.i)
    .map((s) => s.item);
}

// `focus` is free text describing what THIS generation is actually about
// (topic + context, typically) — when given, the instinct/mode lists are
// trimmed to whichever entries best match it, so the model isn't asked to
// weigh its entire personality against one narrow request. Global traits
// (avoid lists, ending patterns, anti-patterns, etc.) are always kept in
// full since they apply regardless of topic and are usually short anyway.
export function summarizeDNAForPrompt(dna, focus = "") {
  if (!dna) return "";
  const lines = [];
  if (dna.core_identity?.core_comedic_brain) lines.push(`Core comedic brain: ${dna.core_identity.core_comedic_brain}`);
  if (dna.core_identity?.one_sentence_summary) lines.push(`Summary: ${dna.core_identity.one_sentence_summary}`);
  if (dna.core_identity?.relationship_comedic_dynamic) lines.push(`Relationship comedic dynamic: ${dna.core_identity.relationship_comedic_dynamic}`);

  const instincts = trimByRelevance(
    dna.strongest_comedic_instincts,
    4,
    focus,
    (i) => `${i.instinct} ${i.description}`
  );
  if (instincts?.length) {
    lines.push(
      "Strongest instincts: " +
        instincts.map((i) => `${i.instinct} (${i.strength}/10) — ${i.description}`).join("; ")
    );
  }

  const modes = trimByRelevance(
    dna.comedy_modes,
    3,
    focus,
    (m) => `${m.name} ${m.description} ${(m.when_to_use || []).join(" ")}`
  );
  if (modes?.length) {
    lines.push(
      "Comedy modes: " +
        modes.map((m) => `${m.name}: ${m.description} [best for: ${(m.when_to_use || []).join(", ")}]`).join(" | ")
    );
  }

  if (dna.preferred_comedy_sources) {
    const sources = Object.entries(dna.preferred_comedy_sources)
      .filter(([, v]) => Number(v) >= 6)
      .map(([k, v]) => `${k} (${v}/10)`);
    if (sources.length) lines.push("Strong comedy sources: " + sources.join(", "));
  }
  if (dna.relationship_logic_patterns?.length) lines.push("Relationship logic patterns: " + dna.relationship_logic_patterns.join("; "));
  if (dna.character_logic_patterns?.length) lines.push("Character logic patterns: " + dna.character_logic_patterns.join("; "));
  if (dna.preferred_escalation_patterns?.length) lines.push("Escalation patterns: " + dna.preferred_escalation_patterns.join("; "));
  if (dna.ending_dna?.length) lines.push("Ending patterns: " + dna.ending_dna.join("; "));
  if (dna.things_to_avoid?.length) lines.push("Avoid: " + dna.things_to_avoid.join("; "));
  if (dna.anti_patterns?.length) lines.push("Anti-patterns: " + dna.anti_patterns.join("; "));
  if (dna.delivery_dna) {
    const d = dna.delivery_dna;
    const delivery = [d.natural_energy, d.deadpan_usage, d.confidence_usage, d.chaos_usage, d.dialogue_rhythm, d.reaction_rhythm]
      .filter(Boolean).join("; ");
    if (delivery) lines.push("Delivery DNA: " + delivery);
  }
  if (dna.preferred_scene_structures?.length) lines.push("Scene structures: " + dna.preferred_scene_structures.join("; "));
  if (dna.contradictions_or_contextual_modes?.length)
    lines.push("Contextual notes: " + dna.contradictions_or_contextual_modes.join("; "));
  return lines.join("\n");
}

